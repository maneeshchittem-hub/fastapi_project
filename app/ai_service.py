import re
import datetime
from typing import Dict, Any, List, Optional
import httpx
from sqlalchemy.orm import Session
from app.config import settings
from app.models import Student
from app.crud import get_student_statistics

def is_ollama_online() -> bool:
    """Check if the local Ollama instance is reachable."""
    try:
        response = httpx.get(f"{settings.OLLAMA_BASE_URL}/api/tags", timeout=2.0)
        return response.status_code == 200
    except Exception:
        return False

def build_student_context(db: Session, max_records: int = 100) -> Dict[str, Any]:
    """
    Safely retrieve student records and aggregate statistics in backend code.
    SECURITY: No dynamic or arbitrary SQL is generated by the LLM.
    """
    stats = get_student_statistics(db)
    students: List[Student] = db.query(Student).limit(max_records).all()
    
    student_records = []
    for s in students:
        student_records.append({
            "id": s.id,
            "name": s.name,
            "date_of_birth": s.date_of_birth.isoformat() if s.date_of_birth else None,
            "email": s.email,
            "phone": s.phone,
            "course": s.course or "Unassigned",
            "enrollment_date": s.enrollment_date.isoformat() if s.enrollment_date else None
        })

    return {
        "stats": stats,
        "records": student_records,
        "count": len(student_records),
        "total_in_db": stats["total_students"]
    }

def format_prompt(question: str, context: Dict[str, Any]) -> str:
    """Construct a grounded prompt with safe database records."""
    stats = context["stats"]
    records = context["records"]

    records_table = "\n".join([
        f"- ID: {r['id']}, Name: {r['name']}, DOB: {r['date_of_birth']}, Course: {r['course']}, Email: {r['email']}, Phone: {r['phone']}, Enrolled: {r['enrollment_date']}"
        for r in records
    ])

    prompt = f"""You are an intelligent records assistant for the Students Database CRUD Application.
Answer the user's question accurately, politely, and concisely using ONLY the verified database records provided below.
DO NOT fabricate or hallucinate any records not present in this context.
If the database does not contain relevant records to answer, state that clearly.

--- DATABASE SUMMARY ---
Total Students: {stats['total_students']}
Courses Distribution: {stats['courses_breakdown']}
Earliest Enrollment: {stats.get('earliest_enrollment')}
Latest Enrollment: {stats.get('latest_enrollment')}

--- STUDENT RECORDS (Total {len(records)} shown) ---
{records_table if records else "No students registered yet."}

--- USER QUESTION ---
{question}

Provide a direct, human-readable answer:"""
    return prompt

def generate_fallback_grounded_answer(question: str, context: Dict[str, Any]) -> str:
    """
    Deterministic rule-based fallback answering common queries directly from records
    when Ollama service is not actively running locally.
    """
    q_lower = question.lower()
    stats = context["stats"]
    records = context["records"]
    total = stats["total_students"]

    # 1. "How many students are there?" / count queries
    if "how many" in q_lower and ("student" in q_lower or "total" in q_lower):
        # Check course specific
        for course, count in stats["courses_breakdown"].items():
            if course and course.lower() in q_lower:
                return f"There are currently {count} student(s) enrolled in the {course} course."
        return f"There are currently {total} student(s) registered in the database."

    # 2. "List students born after <year>" or "born before <year>"
    born_match = re.search(r"born (after|before|in) (\d{4})", q_lower)
    if born_match:
        condition, year_str = born_match.groups()
        year = int(year_str)
        matched = []
        for r in records:
            if r["date_of_birth"]:
                dob_year = int(r["date_of_birth"].split("-")[0])
                if condition == "after" and dob_year > year:
                    matched.append(r)
                elif condition == "before" and dob_year < year:
                    matched.append(r)
                elif condition == "in" and dob_year == year:
                    matched.append(r)
        
        if not matched:
            return f"No students found who were born {condition} {year}."
        
        names_list = ", ".join([f"{m['name']} (DOB: {m['date_of_birth']}, Course: {m['course']})" for m in matched])
        return f"Found {len(matched)} student(s) born {condition} {year}: {names_list}."

    # 3. List courses or breakdown
    if "course" in q_lower and ("list" in q_lower or "what" in q_lower or "breakdown" in q_lower):
        courses_str = ", ".join([f"{k}: {v} student(s)" for k, v in stats["courses_breakdown"].items()])
        return f"Current courses and enrollment counts: {courses_str}."

    # 4. Search specific student name
    for r in records:
        if r["name"].lower() in q_lower:
            return (f"Student profile for {r['name']}: ID #{r['id']}, Course: {r['course']}, "
                    f"Email: {r['email']}, Phone: {r['phone']}, DOB: {r['date_of_birth']}, "
                    f"Enrolled: {r['enrollment_date']}.")

    # Default fallback summary
    if records:
        sample_names = ", ".join([r["name"] for r in records[:5]])
        return (f"The database currently contains {total} students across {len(stats['courses_breakdown'])} courses "
                f"({', '.join(stats['courses_breakdown'].keys())}). Sample students include: {sample_names}.")
    return "The student database is currently empty."

def query_student_assistant(question: str, db: Session) -> Dict[str, Any]:
    """
    Main entrypoint for Natural Language queries.
    1. Fetches grounded DB context safely in Python.
    2. Checks if Ollama is running locally.
    3. If online, queries Ollama (llama3.2:1b).
    4. If offline, returns deterministic grounded response with clear Ollama instructions.
    """
    context = build_student_context(db)
    online = is_ollama_online()

    if online:
        prompt = format_prompt(question, context)
        try:
            with httpx.Client(timeout=settings.OLLAMA_TIMEOUT) as client:
                res = client.post(
                    f"{settings.OLLAMA_BASE_URL}/api/generate",
                    json={
                        "model": settings.OLLAMA_MODEL,
                        "prompt": prompt,
                        "stream": False,
                        "options": {
                            "temperature": 0.2
                        }
                    }
                )
                if res.status_code == 200:
                    answer = res.json().get("response", "").strip()
                    return {
                        "question": question,
                        "answer": answer,
                        "model": settings.OLLAMA_MODEL,
                        "grounded_records_count": context["count"],
                        "ollama_available": True,
                        "context_summary": f"Grounded on {context['count']} record(s)"
                    }
        except Exception:
            # Fall through to offline handler if request failed
            pass

    # Offline fallback grounded response
    fallback_answer = generate_fallback_grounded_answer(question, context)
    help_note = (
        f"\n\n[System Note: Local Ollama model '{settings.OLLAMA_MODEL}' was offline at {settings.OLLAMA_BASE_URL}. "
        f"Answer was generated using grounded record inspection. "
        f"To enable live Ollama LLM generation: run 'ollama run {settings.OLLAMA_MODEL}']"
    )
    return {
        "question": question,
        "answer": fallback_answer + help_note,
        "model": f"grounded-analyzer (offline fallback for {settings.OLLAMA_MODEL})",
        "grounded_records_count": context["count"],
        "ollama_available": False,
        "context_summary": f"Grounded on {context['count']} record(s)"
    }
